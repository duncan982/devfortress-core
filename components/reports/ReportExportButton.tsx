'use client';

import { useState } from 'react';

interface ReportData {
  title: string;
  generatedAt: string;
  dataSource: string;
  sections: Array<{
    heading: string;
    content: string | string[];
  }>;
}

interface ReportExportButtonProps {
  reportData: ReportData;
  className?: string;
}

/**
 * Report Export Button - Generates and downloads reports as PDF, MD, or TXT
 * Used in Insights and Predictive Intelligence pages
 */
export function ReportExportButton({
  reportData,
  className = '',
}: ReportExportButtonProps) {
  const [isExporting, setIsExporting] = useState(false);
  const [showDropdown, setShowDropdown] = useState(false);

  const generateMarkdown = (): string => {
    let md = `# ${reportData.title}\n\n`;
    md += `**Generated:** ${new Date(reportData.generatedAt).toLocaleString()}\n`;
    md += `**Data Source:** ${reportData.dataSource}\n\n`;
    md += `---\n\n`;

    for (const section of reportData.sections) {
      md += `## ${section.heading}\n\n`;
      if (Array.isArray(section.content)) {
        for (const item of section.content) {
          md += `- ${item}\n`;
        }
      } else {
        md += `${section.content}\n`;
      }
      md += '\n';
    }

    md += `---\n\n`;
    md += `*Report generated by [Devfortress](https://devfortress.net) — API Security Platform*\n`;
    md += `*Build · Defend · Collect · Learn*\n`;
    return md;
  };

  const generatePlainText = (): string => {
    let txt = `${reportData.title}\n`;
    txt += `${'='.repeat(reportData.title.length)}\n\n`;
    txt += `Generated: ${new Date(reportData.generatedAt).toLocaleString()}\n`;
    txt += `Data Source: ${reportData.dataSource}\n\n`;
    txt += `${'─'.repeat(60)}\n\n`;

    for (const section of reportData.sections) {
      txt += `${section.heading}\n`;
      txt += `${'-'.repeat(section.heading.length)}\n\n`;
      if (Array.isArray(section.content)) {
        for (const item of section.content) {
          txt += `  • ${item}\n`;
        }
      } else {
        txt += `${section.content}\n`;
      }
      txt += '\n';
    }

    txt += `${'─'.repeat(60)}\n`;
    txt += `Report generated by Devfortress (devfortress.net)\n`;
    txt += `Build · Defend · Collect · Learn\n`;
    return txt;
  };

  const downloadFile = (content: string, filename: string, mimeType: string) => {
    const blob = new Blob([content], { type: mimeType });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const handleExport = async (format: 'pdf' | 'md' | 'txt') => {
    setIsExporting(true);
    setShowDropdown(false);

    try {
      const timestamp = new Date().toISOString().slice(0, 10);
      const baseFilename = `devfortress-report-${timestamp}`;

      if (format === 'md') {
        const content = generateMarkdown();
        downloadFile(content, `${baseFilename}.md`, 'text/markdown');
      } else if (format === 'txt') {
        const content = generatePlainText();
        downloadFile(content, `${baseFilename}.txt`, 'text/plain');
      } else if (format === 'pdf') {
        // Generate PDF using browser print functionality
        const content = generateMarkdown();
        const printWindow = window.open('', '_blank');
        if (printWindow) {
          printWindow.document.write(`
            <!DOCTYPE html>
            <html>
            <head>
              <title>${reportData.title}</title>
              <style>
                body { font-family: 'Segoe UI', system-ui, sans-serif; padding: 40px; max-width: 800px; margin: 0 auto; color: #1a1a2e; line-height: 1.6; }
                h1 { color: #0a0e1a; border-bottom: 3px solid #c0392b; padding-bottom: 12px; margin-bottom: 20px; font-size: 24px; }
                h2 { color: #1a1f3a; margin-top: 24px; font-size: 18px; border-bottom: 1px solid #e0e0e0; padding-bottom: 8px; }
                .meta { color: #666; font-size: 13px; margin-bottom: 20px; padding: 12px; background: #f8f8f8; border-radius: 6px; }
                ul { padding-left: 20px; }
                li { margin-bottom: 6px; }
                p { margin-bottom: 10px; }
                .footer { margin-top: 40px; padding-top: 20px; border-top: 2px solid #e0e0e0; color: #888; font-size: 11px; text-align: center; }
                .badge { display: inline-block; background: #c0392b; color: white; padding: 2px 8px; border-radius: 3px; font-size: 10px; letter-spacing: 1px; text-transform: uppercase; }
                @media print { body { padding: 20px; } }
              </style>
            </head>
            <body>
              <div style="display: flex; align-items: center; gap: 12px; margin-bottom: 24px;">
                <span style="font-weight: 800; font-size: 20px;">DEVFORTRESS</span>
                <span class="badge">Security Report</span>
              </div>
              <h1>${reportData.title}</h1>
              <div class="meta">
                <strong>Generated:</strong> ${new Date(reportData.generatedAt).toLocaleString()}<br>
                <strong>Data Source:</strong> ${reportData.dataSource}
              </div>
              ${reportData.sections
                .map(
                  (section) => `
                <h2>${section.heading}</h2>
                ${
                  Array.isArray(section.content)
                    ? `<ul>${section.content.map((item) => `<li>${item}</li>`).join('')}</ul>`
                    : `<p>${section.content.replace(/\n/g, '<br>')}</p>`
                }
              `
                )
                .join('')}
              <div class="footer">
                <p>Report generated by Devfortress — API Security Platform</p>
                <p>Build · Defend · Collect · Learn | devfortress.net</p>
              </div>
            </body>
            </html>
          `);
          printWindow.document.close();
          setTimeout(() => {
            printWindow.print();
          }, 500);
        }
      }
    } catch (err) {
      console.error('Export failed:', err);
    } finally {
      setIsExporting(false);
    }
  };

  return (
    <div className={`relative ${className}`}>
      <button
        onClick={() => setShowDropdown(!showDropdown)}
        disabled={isExporting}
        className="inline-flex items-center gap-2 rounded-lg border border-neutral-300 bg-white px-4 py-2 text-sm font-semibold text-neutral-700 hover:bg-neutral-50 disabled:opacity-50 dark:border-neutral-600 dark:bg-neutral-800 dark:text-neutral-200 dark:hover:bg-neutral-700"
      >
        {isExporting ? (
          <>
            <span className="h-4 w-4 animate-spin rounded-full border-2 border-neutral-400 border-t-neutral-700" />
            Exporting...
          </>
        ) : (
          <>
            📄 Export Report
            <svg
              className={`h-4 w-4 transition-transform ${showDropdown ? 'rotate-180' : ''}`}
              fill="none"
              viewBox="0 0 24 24"
              stroke="currentColor"
            >
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M19 9l-7 7-7-7" />
            </svg>
          </>
        )}
      </button>

      {showDropdown && (
        <div className="absolute right-0 top-full z-10 mt-1 w-48 rounded-lg border border-neutral-200 bg-white py-1 shadow-lg dark:border-neutral-700 dark:bg-neutral-800">
          <button
            onClick={() => handleExport('pdf')}
            className="flex w-full items-center gap-3 px-4 py-2 text-sm text-neutral-700 hover:bg-neutral-100 dark:text-neutral-200 dark:hover:bg-neutral-700"
          >
            <span className="text-red-500">📕</span>
            Export as PDF
          </button>
          <button
            onClick={() => handleExport('md')}
            className="flex w-full items-center gap-3 px-4 py-2 text-sm text-neutral-700 hover:bg-neutral-100 dark:text-neutral-200 dark:hover:bg-neutral-700"
          >
            <span className="text-blue-500">📘</span>
            Export as Markdown
          </button>
          <button
            onClick={() => handleExport('txt')}
            className="flex w-full items-center gap-3 px-4 py-2 text-sm text-neutral-700 hover:bg-neutral-100 dark:text-neutral-200 dark:hover:bg-neutral-700"
          >
            <span className="text-neutral-500">📃</span>
            Export as Text
          </button>
        </div>
      )}
    </div>
  );
}
