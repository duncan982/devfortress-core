/**
 * White-Label Report Branding Configuration
 *
 * Allows ENTERPRISE subscribers and consulting clients to customize
 * report branding (logo, colors, company name).
 *
 * C5: White-Label Report Branding (Enterprise)
 */

export interface BrandingConfig {
  /** Company/organization name shown on reports */
  companyName: string;
  /** URL to company logo (displayed in report header) */
  logoUrl?: string;
  /** Primary brand color (hex, e.g. '#1a56db') */
  primaryColor: string;
  /** Secondary/accent brand color */
  accentColor: string;
  /** Footer text for reports */
  footerText?: string;
  /** Contact email shown on reports */
  contactEmail?: string;
  /** Custom domain for report sharing links */
  reportDomain?: string;
}

/** Default DevFortress branding */
export const DEFAULT_BRANDING: BrandingConfig = {
  companyName: 'DevFortress',
  logoUrl: '/devfortress-logo.svg',
  primaryColor: '#4f46e5',
  accentColor: '#0ea5e9',
  footerText: 'Generated by DevFortress — Enterprise API Security Platform',
  contactEmail: 'security@devfortress.net',
};

/**
 * Parse branding config stored in ConsultingClient.branding JSON field.
 * Returns default branding if config is null/invalid.
 */
export function parseBrandingConfig(brandingJson: unknown): BrandingConfig {
  if (!brandingJson || typeof brandingJson !== 'object') {
    return { ...DEFAULT_BRANDING };
  }

  const raw = brandingJson as Record<string, unknown>;

  return {
    companyName:
      typeof raw.companyName === 'string' && raw.companyName.length > 0
        ? raw.companyName
        : DEFAULT_BRANDING.companyName,
    logoUrl:
      typeof raw.logoUrl === 'string' && raw.logoUrl.length > 0
        ? raw.logoUrl
        : DEFAULT_BRANDING.logoUrl,
    primaryColor:
      typeof raw.primaryColor === 'string' &&
      /^#[0-9a-fA-F]{6}$/.test(raw.primaryColor)
        ? raw.primaryColor
        : DEFAULT_BRANDING.primaryColor,
    accentColor:
      typeof raw.accentColor === 'string' &&
      /^#[0-9a-fA-F]{6}$/.test(raw.accentColor)
        ? raw.accentColor
        : DEFAULT_BRANDING.accentColor,
    footerText:
      typeof raw.footerText === 'string'
        ? raw.footerText
        : DEFAULT_BRANDING.footerText,
    contactEmail:
      typeof raw.contactEmail === 'string'
        ? raw.contactEmail
        : DEFAULT_BRANDING.contactEmail,
    reportDomain:
      typeof raw.reportDomain === 'string' ? raw.reportDomain : undefined,
  };
}

/**
 * Validate branding config input from user.
 * Returns sanitized config or error message.
 */
export function validateBrandingConfig(
  input: unknown
):
  | { valid: true; config: Partial<BrandingConfig> }
  | { valid: false; error: string } {
  if (!input || typeof input !== 'object') {
    return { valid: false, error: 'Branding config must be an object' };
  }

  const raw = input as Record<string, unknown>;
  const config: Partial<BrandingConfig> = {};

  if (raw.companyName !== undefined) {
    if (typeof raw.companyName !== 'string' || raw.companyName.length > 200) {
      return {
        valid: false,
        error: 'companyName must be a string (max 200 chars)',
      };
    }
    config.companyName = raw.companyName.trim();
  }

  if (raw.logoUrl !== undefined) {
    if (typeof raw.logoUrl !== 'string' || raw.logoUrl.length > 2000) {
      return {
        valid: false,
        error: 'logoUrl must be a valid URL (max 2000 chars)',
      };
    }
    config.logoUrl = raw.logoUrl.trim();
  }

  if (raw.primaryColor !== undefined) {
    if (
      typeof raw.primaryColor !== 'string' ||
      !/^#[0-9a-fA-F]{6}$/.test(raw.primaryColor)
    ) {
      return {
        valid: false,
        error: 'primaryColor must be a hex color (e.g. #1a56db)',
      };
    }
    config.primaryColor = raw.primaryColor;
  }

  if (raw.accentColor !== undefined) {
    if (
      typeof raw.accentColor !== 'string' ||
      !/^#[0-9a-fA-F]{6}$/.test(raw.accentColor)
    ) {
      return {
        valid: false,
        error: 'accentColor must be a hex color (e.g. #0ea5e9)',
      };
    }
    config.accentColor = raw.accentColor;
  }

  if (raw.footerText !== undefined) {
    if (typeof raw.footerText !== 'string' || raw.footerText.length > 500) {
      return {
        valid: false,
        error: 'footerText must be a string (max 500 chars)',
      };
    }
    config.footerText = raw.footerText.trim();
  }

  if (raw.contactEmail !== undefined) {
    if (
      typeof raw.contactEmail !== 'string' ||
      !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(raw.contactEmail)
    ) {
      return { valid: false, error: 'contactEmail must be a valid email' };
    }
    config.contactEmail = raw.contactEmail.trim();
  }

  if (raw.reportDomain !== undefined) {
    if (typeof raw.reportDomain !== 'string' || raw.reportDomain.length > 200) {
      return {
        valid: false,
        error: 'reportDomain must be a string (max 200 chars)',
      };
    }
    config.reportDomain = raw.reportDomain.trim();
  }

  return { valid: true, config };
}

